// local/staticApps.js
// ─────────────────────────────────────────────────────────────────────────────
// Offline Edition: the restaurant PC serves the four built web apps itself,
// so phones, the kitchen screen and the admin PC need nothing but the
// restaurant Wi-Fi. LOCAL_PRIMARY only (server.js) — the cloud keeps its
// own hosting.
//
// One port per app, because every build references root paths (/assets,
// /config.js, /sw.js) and the service worker's scope is the origin.
//   customer 8080 · admin 8081 · waiter 8082 · kitchen 8083   (LOCAL_PORT_*)
//
// Backend address: each app reads window.__ZEN_CONFIG__.apiUrl from
// /config.js (src/config/runtimeConfig.js). We serve a generated /config.js
// that points the app at THIS server's API port on whatever address the
// phone used to open the page (http://192.168.1.20:8082 → :5000/api), so no
// IP is baked into a build and a DHCP address change needs no rebuild. The
// build's own config.js is appended unchanged, so other keys in it (e.g.
// googleMapsKey) still apply; its apiUrl is overridden by ours because it
// merges with Object.assign({...file}, window.__ZEN_CONFIG__).
// ─────────────────────────────────────────────────────────────────────────────

import fs from "node:fs";
import path from "node:path";
import http from "node:http";
import { fileURLToPath } from "node:url";
import express from "express";

export const LOCAL_APPS = Object.freeze([
  { name: "customer", envPort: "LOCAL_PORT_CUSTOMER", defaultPort: 8080 },
  { name: "admin",    envPort: "LOCAL_PORT_ADMIN",    defaultPort: 8081 },
  { name: "waiter",   envPort: "LOCAL_PORT_WAITER",   defaultPort: 8082 },
  { name: "kitchen",  envPort: "LOCAL_PORT_KITCHEN",  defaultPort: 8083 },
]);

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");

const parsePort = (raw, fallback) => {
  const n = Number(String(raw ?? "").trim() || fallback);
  return Number.isInteger(n) && n > 0 && n < 65536 ? n : null;
};

/**
 * Pure: env → [{ name, port, dir }].
 * LOCAL_APPS_DIR=<folder> → <folder>/<name> (an installed bundle);
 * unset → <repo>/<name>/dist (a developer checkout after `npm run build`).
 */
export const resolveAppPlan = (env = process.env) => {
  const base = typeof env.LOCAL_APPS_DIR === "string" && env.LOCAL_APPS_DIR.trim() ? path.resolve(env.LOCAL_APPS_DIR.trim()) : null;
  return LOCAL_APPS.map((a) => ({
    name: a.name,
    port: parsePort(env[a.envPort], a.defaultPort),
    dir: base ? path.join(base, a.name) : path.join(REPO_ROOT, a.name, "dist"),
  }));
};

/** Pure: the /config.js we serve. apiPort is a number; the build's own file text is appended. */
export const buildRuntimeConfigJs = ({ apiPort, appName, buildConfigJs = "" }) => [
  `// Generated by the Zen OS local server (Offline Edition) for the ${appName} app.`,
  `// The backend is this same PC, on port ${apiPort}, at the address this page was opened with.`,
  `window.__ZEN_CONFIG__ = Object.assign({}, window.__ZEN_CONFIG__, {`,
  `  apiUrl: window.location.protocol + "//" + window.location.hostname + ":" + ${JSON.stringify(String(apiPort))} + "/api",`,
  `  localServer: true`,
  `});`,
  ``,
  buildConfigJs,
].join("\n");

// Files that must always be revalidated: a stale sw.js/index.html pins
// devices to an old build; a stale config.js to an old backend address.
const NO_CACHE = new Set(["index.html", "sw.js", "config.js", "manifest.webmanifest", "firebase-messaging-sw.js"]);

/** Express app for one built web app folder. */
export const createAppHost = ({ appName, dir, apiPort }) => {
  const app = express();
  app.disable("x-powered-by");

  const buildConfigPath = path.join(dir, "config.js");
  app.get("/config.js", (_req, res) => {
    let buildConfigJs = "";
    try { buildConfigJs = fs.readFileSync(buildConfigPath, "utf8"); } catch { /* build without one — fine */ }
    res.set("Cache-Control", "no-cache");
    res.type("application/javascript").send(buildRuntimeConfigJs({ apiPort, appName, buildConfigJs }));
  });

  app.use(express.static(dir, {
    index: "index.html",
    dotfiles: "ignore",
    setHeaders: (res, filePath) => {
      const base = path.basename(filePath);
      if (NO_CACHE.has(base)) res.set("Cache-Control", "no-cache");
      else if (filePath.includes(`${path.sep}assets${path.sep}`)) res.set("Cache-Control", "public, max-age=31536000, immutable");
    },
  }));

  // SPA fallback: a page navigation (/orders, /tables/3 …) gets index.html.
  // A missing file (/assets/x.js, /logo.png) stays a 404 — never index.html,
  // or the browser would try to run HTML as JavaScript.
  app.use((req, res) => {
    const wantsPage = (req.method === "GET" || req.method === "HEAD")
      && !path.extname(req.path)
      && (req.accepts(["html", "json"]) === "html");
    if (!wantsPage) return res.status(404).type("text/plain").send("Not found");
    res.set("Cache-Control", "no-cache");
    return res.sendFile("index.html", { root: dir });
  });
  return app;
};

/**
 * Starts one HTTP server per built app. A missing build or a busy port is
 * reported (health + log) and skipped — it never stops the API itself.
 * @returns {{ getApps: () => object, close: () => Promise<void> }}
 */
export const startLocalAppServers = ({ env = process.env, apiPort, log = console } = {}) => {
  const state = {};
  const servers = [];
  for (const plan of resolveAppPlan(env)) {
    const entry = { port: plan.port, dir: plan.dir, state: "starting", reason: null };
    state[plan.name] = entry;
    if (!plan.port) { Object.assign(entry, { state: "not configured", reason: "invalid port" }); continue; }
    if (plan.port === Number(apiPort)) { Object.assign(entry, { state: "not configured", reason: `port ${plan.port} is the API port` }); continue; }
    if (!fs.existsSync(path.join(plan.dir, "index.html"))) {
      Object.assign(entry, { state: "not built", reason: "no index.html — run npm run build in this app" });
      log.warn(`⚠️  LOCAL MODE: ${plan.name} app not served — no build at ${plan.dir}`);
      continue;
    }
    const server = http.createServer(createAppHost({ appName: plan.name, dir: plan.dir, apiPort }));
    server.on("error", (err) => {
      Object.assign(entry, { state: "failed", reason: err.code === "EADDRINUSE" ? `port ${plan.port} already in use` : err.message });
      log.error(`❌ LOCAL MODE: ${plan.name} app could not start on port ${plan.port}: ${entry.reason}`);
    });
    server.listen(plan.port, () => {
      entry.state = "serving";
      log.log(`🌐 ${plan.name.padEnd(8)} app → http://<this-PC>:${plan.port}`);
    });
    servers.push(server);
  }
  return {
    // Copies only — callers can't mutate the live state. `dir` is a local
    // path: fine for the LAN-only health page, never sent to the cloud.
    getApps: () => Object.fromEntries(Object.entries(state).map(([k, v]) => [k, { ...v }])),
    close: () => Promise.all(servers.map((s) => new Promise((r) => (s.listening ? s.close(() => r()) : r())))).then(() => {}),
  };
};
